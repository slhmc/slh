import { expect, test } from '@playwright/test';
test('shared and sequential port preferences apply to new servers', async ({page}) => {
  await page.goto('/#/local-servers');
  await page.getByRole('button',{name:'Create server',exact:true}).click();
  let dialog=page.getByRole('dialog');
  await dialog.getByRole('tab',{name:'Network',exact:true}).click();
  const allocatedPort = Number(await dialog.getByRole('spinbutton',{name:'Port',exact:true}).inputValue());
  await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('First port');
  await dialog.getByRole('checkbox',{name:/I accept the Minecraft EULA/}).check();
  await dialog.getByRole('button',{name:'Create server',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await page.goto('/#/settings/servers');
  await page.getByRole('combobox',{name:'New server ports',exact:true}).selectOption('shared');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.goto('/#/local-servers');
  await page.getByRole('button',{name:'Create server',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('tab',{name:'Network',exact:true}).click();
  await expect(dialog.getByRole('spinbutton',{name:'Port',exact:true})).toHaveValue('25565');
  await page.keyboard.press('Escape');
  await page.goto('/#/settings/servers');
  await page.getByRole('combobox',{name:'New server ports',exact:true}).selectOption('increment');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.goto('/#/local-servers');
  await page.getByRole('button',{name:'Create server',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('tab',{name:'Network',exact:true}).click();
  await expect(dialog.getByRole('spinbutton',{name:'Port',exact:true})).toHaveValue(String(allocatedPort + 1));
});
test('empty server name is highlighted and installation does not retain the dialog', async ({page}) => {
  await page.goto('/#/local-servers');
  await page.getByRole('button',{name:'Create server',exact:true}).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Create server',exact:true}).click();
  await expect(dialog.getByRole('textbox',{name:'Name',exact:true})).toHaveAttribute('aria-invalid','true');
  await expect(dialog.getByRole('textbox',{name:'Name',exact:true})).toBeFocused();
  await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('Background test');
  await dialog.getByRole('checkbox',{name:/I accept the Minecraft EULA/}).check();
  await dialog.getByRole('button',{name:'Create server',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('button',{name:'Background test',exact:true})).toBeVisible();
});
