import { ActionVisibilityMenu } from "../common/ActionVisibilityMenu";
import { useEffect, useRef, useState, type PointerEvent as ReactPointerEvent } from "react";
import { DetailTabs } from "../common/LibraryChrome";
import { FileText, Wrench, Info, PuzzlePiece } from "../icons";
import { useUiText } from "../../i18n/UiText";
import { moveBefore, normalizeServerTabs, toggleServerTab, type ServerTab } from "../../lib/serverPresentation";
import type { ServerLibraryView } from "../../lib/localServers";
import detail from "../../routes/Instance/InstancePage.module.css";
import extra from "../../routes/LocalServers/ServerLibrary.module.css";

const icons = { overview: Info, settings: Wrench, console: FileText, plugins: PuzzlePiece };
const labels = { overview: "serverLibrary.overview", settings: "navigation.settings", console: "localServers.console", plugins: "serverWorkspace.plugins" };
export function ServerTabs({ view, current, position, onChange, onSelect }: {
  view: ServerLibraryView; current: string; position: string; onChange: (patch: Partial<ServerLibraryView>) => void;
  onSelect: (id: string) => void;
}) {
  const t = useUiText();
  const { order, visible } = normalizeServerTabs(view);
  const [menu, setMenu] = useState<{ x: number; y: number } | null>(null);
  const nav = useRef<HTMLElement | null>(null);
  const drag = useRef<{ id: ServerTab; x: number; y: number; active: boolean; node: HTMLElement; pointerId: number } | null>(null);
  const [drop, setDrop] = useState<{ id: ServerTab; after: boolean } | null>(null);
  const suppress = useRef(false);
  const begin = (event: ReactPointerEvent<HTMLElement>, id: ServerTab) => {
    if (event.button !== 0) return;
    suppress.current = false;
    event.currentTarget.setPointerCapture(event.pointerId);
    drag.current = { id, x: event.clientX, y: event.clientY, active: false, node: event.currentTarget, pointerId: event.pointerId };
  };
  const openMenu = (x: number, y: number) => setMenu({ x, y });
  useEffect(() => {
    const escape = (event: KeyboardEvent) => { if (event.key === "Escape") { setMenu(null); nav.current?.querySelector<HTMLElement>("[aria-current]")?.focus(); } };
    const cancel = () => { const value = drag.current; if (value?.node.hasPointerCapture(value.pointerId)) value.node.releasePointerCapture(value.pointerId); drag.current = null; setDrop(null); suppress.current = false; };
    const targetAt = (event: PointerEvent) => {
      const node = document.elementFromPoint(event.clientX, event.clientY)?.closest<HTMLElement>("[data-server-tab],[data-server-tab-menu]");
      const id = node?.dataset.serverTab ?? node?.dataset.serverTabMenu;
      if (!node || !id) return null;
      const rect = node.getBoundingClientRect();
      const horizontal = !node.dataset.serverTabMenu && (innerWidth <= 720 || position === "top" || position === "bottom");
      return { id: id as ServerTab, after: horizontal ? event.clientX > rect.x + rect.width / 2 : event.clientY > rect.y + rect.height / 2 };
    };
    const move = (event: PointerEvent) => {
      const value = drag.current;
      if (!value || Math.hypot(event.clientX - value.x, event.clientY - value.y) < 8 && !value.active) return;
      value.active = true; setDrop(targetAt(event));
    };
    const end = (event: PointerEvent) => {
      const value = drag.current;
      const target = targetAt(event);
      if (value?.node.hasPointerCapture(value.pointerId)) value.node.releasePointerCapture(value.pointerId);
      drag.current = null; setDrop(null);
      if (!value?.active) return;
      suppress.current = true;
      if (target && target.id !== value.id) onChange({ tabOrder: moveBefore(order, value.id, target.id, target.after) });
      // Only the click generated by this release is suppressed.
      window.setTimeout(() => { suppress.current = false; }, 0);
    };
    window.addEventListener("keydown", escape);
    window.addEventListener("pointermove", move); window.addEventListener("pointerup", end);
    window.addEventListener("pointercancel", cancel); window.addEventListener("blur", cancel);
    return () => {
      window.removeEventListener("keydown", escape);
      window.removeEventListener("pointermove", move); window.removeEventListener("pointerup", end);
      window.removeEventListener("pointercancel", cancel); window.removeEventListener("blur", cancel);
    };
  }, [order.join("|"), position, onChange]);
  const toggle = (id: ServerTab) => {
    if (suppress.current) return;
    const next = toggleServerTab(view, id, current);
    onChange(next.view);
    if (next.current !== current) onSelect(next.current);
  };
  return <>
    <DetailTabs aria-label={t("serverWorkspace.serverSections")} data-slh-context-menu="true"
      onContextMenu={event => { event.preventDefault(); nav.current = event.currentTarget; openMenu(event.clientX, event.clientY); }}
      onKeyDown={event => { if (event.key === "ContextMenu" || event.shiftKey && event.key === "F10") { event.preventDefault(); nav.current = event.currentTarget; const rect = (event.target as HTMLElement).getBoundingClientRect(); openMenu(rect.x, rect.bottom); } }}>
      {visible.map(id => { const Icon = icons[id]; return <button type="button" key={id} data-server-tab={id} aria-label={t(labels[id])} title={t(labels[id])} className={`${current === id ? detail.active : ""} ${drop?.id === id ? drop.after ? extra.insertAfter : extra.insertBefore : ""}`} aria-current={current === id ? "page" : undefined} onPointerDown={event => begin(event, id)} onClick={() => { if (!suppress.current) onSelect(id); }}><Icon size={15} /><span data-minimal-text>{t(labels[id])}</span></button>; })}
    </DetailTabs>
    {menu ? <ActionVisibilityMenu at={menu} title={t("serverWorkspace.serverSections")} items={order.map(id => ({ id, label: t(labels[id]), Icon: icons[id], checked: visible.includes(id), disabled: visible.length === 1 && visible.includes(id), reorderable: true, separator: id === "settings" }))} onClose={() => setMenu(null)} onToggle={id => toggle(id as ServerTab)} onReorder={tabOrder => onChange({ tabOrder })} /> : null}
  </>;
}
